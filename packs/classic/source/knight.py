"""The classic pack's knight, drawn by hand as text art (a Stable Diffusion draft was the first reference).
16x16, 3 colours + transparent: K black outline, R red tunic, S grey armour.

Views: side (faces right; mirrored for left), down (front), up (back) x 2 frames (0 = stand, 1 = stride).
Usage: python packs/classic/source/knight.py   -> packs/classic/cast/hero_<view>_<frame>.png
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))  # the repo root
from content.pictures import save_folder
from shared.palettes import NES

COLOURS = {"K": 0x0F, "R": 0x16, "S": 0x10}

_HEAD_SIDE = """
.....KKKKK......
....KSSSSSK.....
...KSSSSSSSK....
...KSSSSKKKK....
...KSSSSSSSK....
....KSSSSSK.....
....KRRRRRK.....
...KRRRRRRRK....
...KRRRRKSSK....
...KRRRRRRKK....
...KKKKKKKK.....
...KRRRRRRK....."""
_HEAD_FRONT = """
.....KKKKKK.....
....KSSSSSSK....
....KSSSSSSK....
....KS{v}SK....
....KSSSSSSK....
.....KSSSSK.....
...KKRRRRRRKK...
..KSKRRRRRRKSK..
..KSKRRRRRRKSK..
..KKKRRRRRRKKK..
....KKKKKKKK....
....KRRRRRRK...."""

SPRITES = {
    ("side", 0): _HEAD_SIDE + """
....KRRRRK......
....KSSKSSK.....
....KSSKSSSK....
....KKKKKKKK....""",
    ("side", 1): _HEAD_SIDE + """
...KRRKKRRK.....
..KSSK..KSSK....
.KSSSK..KSSSK...
.KKKK....KKKK...""",
    ("down", 0): _HEAD_FRONT.format(v="KKKK") + """
....KRRKKRRK....
....KSSKKSSK....
....KSSKKSSK....
....KKKKKKKK....""",
    ("down", 1): _HEAD_FRONT.format(v="KKKK") + """
....KRRKKRRK....
....KSSKKSSK....
....KKKKKSSK....
.........KKK....""",
    ("up", 0): _HEAD_FRONT.format(v="SSSS") + """
....KRRKKRRK....
....KSSKKSSK....
....KSSKKSSK....
....KKKKKKKK....""",
    ("up", 1): _HEAD_FRONT.format(v="SSSS") + """
....KRRKKRRK....
....KSSKKSSK....
....KSSKKKKK....
....KKK.........""",
}


def to_rgba(art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), [len(r) for r in rows]
    out = np.zeros((16, 16, 4), np.uint8)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in COLOURS:
                out[y, x] = (*NES[COLOURS[ch]], 255)
    return out


def pictures():
    """picture name -> RGBA ("side" is the right-facing view; the look mirrors it for left)."""
    return {f"hero_{'right' if view == 'side' else view}_{frame}": to_rgba(art)
            for (view, frame), art in SPRITES.items()}


if __name__ == "__main__":
    save_folder(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "cast"), pictures())
